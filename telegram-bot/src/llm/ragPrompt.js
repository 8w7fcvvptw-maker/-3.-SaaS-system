/**
 * @typedef {{ content: string; metadata?: Record<string, unknown>; similarity?: number }} KnowledgeChunk
 */

/** Дословная формулировка при нехватке фактов в найденных фрагментах */
export const INSUFFICIENT_KNOWLEDGE_PHRASE =
  "В базе знаний нет точной информации по этому вопросу";

export const NO_KNOWLEDGE_REPLY = `${INSUFFICIENT_KNOWLEDGE_PHRASE}. Если нужны детали под вашу задачу — оставьте заявку через «Оставить заявку», менеджер уточнит условия.`;

/**
 * @param {KnowledgeChunk[]} chunks
 * @returns {string}
 */
export function buildKnowledgeContextPrompt(chunks) {
  const body = chunks
    .map((chunk, index) => {
      const source =
        typeof chunk.metadata?.source === "string" ? chunk.metadata.source : "неизвестный источник";
      const similarity =
        typeof chunk.similarity === "number" ? chunk.similarity.toFixed(2) : "—";

      return `[${index + 1}] Источник: ${source} (сходство ${similarity})
${chunk.content}`;
    })
    .join("\n\n");

  return `Ниже — единственный источник фактов для ответа. Следующее сообщение пользователя нужно разобрать только по этим фрагментам.

Главное правило:
- Любой факт о продукте, тарифе или функции — только если он прямо есть в фрагментах. Иначе не утверждай его.

Если ответа нет или он неполный:
- Начни ответ с фразы дословно: «${INSUFFICIENT_KNOWLEDGE_PHRASE}».
- Не додумывай и не «обобщай». Запрещены уверенные догадки и общие фразы вроде «в целом система позволяет», «обычно доступно», «как правило входит», если этого нет в тексте фрагментов.
- После фразы кратко предложи оставить заявку через «Оставить заявку», чтобы менеджер уточнил детали. Не обещай срок ответа.

Если ответ есть в фрагментах:
- 2–3 коротких предложения по делу, дружелюбно, на русском. Без вступлений и воды.
- Называй только те тарифы (Start, Pro, Business), функции и условия, которые явно упомянуты во фрагментах.
- Не называй цены, сроки, скидки, пробные периоды — даже если пользователь спрашивает. Предложи заявку менеджеру.
- Не упоминай слова «фрагмент», «база знаний», «поиск», «контекст» в ответе пользователю.

Запрещено (даже при похожих фрагментах):
- Придумывать тарифы, пакеты, функции, интеграции, лимиты, цены.
- Отвечать общими словами без конкретики из текста ниже.

--- Фрагменты ---
${body}
--- Конец фрагментов ---`;
}
